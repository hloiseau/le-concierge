const MaxSources = 3

type Source struct {
	Title       string `json:"title"`
	URL         string `json:"url"`
	Text        string `json:"text"`
	Kind        string `json:"kind"` // snippet, page, or video (metadata only).
	PublishedAt string `json:"publishedAt,omitempty"`
	Author      string `json:"author,omitempty"`
}

type Result struct {
	RetrievedAt string   `json:"retrievedAt"`
	Sources     []Source `json:"sources"`
}

func (r Result) Validate() bool {
	if _, err := time.Parse(time.RFC3339, r.RetrievedAt); err != nil || len(r.Sources) < 1 || len(r.Sources) > MaxSources {
		return false
	}
	for _, s := range r.Sources {
		if !PublicURL(s.URL) || len(s.URL) > 300 || s.Title == "" || s.Text == "" || utf8.RuneCountInString(s.Title) > 160 || utf8.RuneCountInString(s.Text) > 1800 || len(s.PublishedAt) > 80 || utf8.RuneCountInString(s.Author) > 160 || (s.Kind != "snippet" && s.Kind != "page" && s.Kind != "video") {
			return false
		}
	}
	return true
}

// Links are rendered by the application, never generated by the model.
func (r Result) Links(ids []int) string {
	var lines []string
	for _, id := range ids {
		s := r.Sources[id-1]
		title := strings.NewReplacer("[", "", "]", "", "*", "", "_", "", "`", "", "<", "", ">", "").Replace(s.Title)
		target := strings.NewReplacer("(", "%28", ")", "%29", "<", "%3C", ">", "%3E").Replace(s.URL)
		lines = append(lines, fmt.Sprintf("[%d] [%s](<%s>)", id, clip(title, 90), target))
	}
	return strings.Join(lines, "\n")
}

func (r Result) Fallback() string {
	var ids []int
	for i := range r.Sources {
		ids = append(ids, i+1)
	}
	return "Voici les sources trouvées ; je n’ai pas pu en faire une synthèse fiable.\n" + r.Links(ids)
}

type Client struct {
	endpoint string
	search   *http.Client
	public   *http.Client
	blocked  map[string]bool
	origin   string
	domain   string
	lookup   func(context.Context, string, string) ([]netip.Addr, error)
	dial     func(context.Context, string, string) (net.Conn, error)
}

// endpoint is a trusted operator setting, never supplied by a model or member.
func New(endpoint, publicOrigin string, serviceURLs ...string) *Client {
	c := &Client{endpoint: strings.TrimRight(endpoint, "/"), blocked: map[string]bool{}, search: &http.Client{Timeout: 6 * time.Second, CheckRedirect: func(*http.Request, []*http.Request) error { return http.ErrUseLastResponse }}}
	c.lookup = net.DefaultResolver.LookupNetIP
	c.dial = (&net.Dialer{Timeout: 3 * time.Second}).DialContext
	if u, err := url.Parse(publicOrigin); err == nil {
		c.origin = u.Hostname()
		c.domain, _ = publicsuffix.EffectiveTLDPlusOne(c.origin)
	}
	for _, raw := range append(serviceURLs, endpoint, publicOrigin) {
		if u, err := url.Parse(raw); err == nil && u.Hostname() != "" {
			c.blocked[strings.ToLower(strings.TrimSuffix(u.Hostname(), "."))] = true
		}
	}
	c.public = c.publicClient()
	return c
}

func clip(s string, n int) string {
	s = strings.Join(strings.Fields(strings.Map(func(r rune) rune {
		if unicode.IsControl(r) {
			return ' '
		}
		return r
	}, s)), " ")
	if utf8.RuneCountInString(s) > n {
		s = string([]rune(s)[:n-1]) + "…"
	}
	return s
}

func get(ctx context.Context, client *http.Client, target, accept string, limit int) ([]byte, *http.Response, error) {
	req, err := http.NewRequestWithContext(ctx, "GET", target, nil)
	if err != nil {
		return nil, nil, ErrDenied
	}
	req.Header.Set("Accept", accept)
	req.Header.Set("User-Agent", "Eris-Web/1.0 (+https://github.com/hloiseau/le-concierge)")
	resp, err := client.Do(req)
	if err != nil {
		return nil, nil, ErrUnavailable
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		return nil, resp, ErrUnavailable
	}
	b, err := io.ReadAll(io.LimitReader(resp.Body, int64(limit+1)))
	if err != nil || len(b) > limit {
		return nil, resp, ErrUnavailable
	}
	return b, resp, nil
}

func (c *Client) Search(ctx context.Context, query string, youtube bool) (Result, error) {
	if c.endpoint == "" || clip(query, 200) != query || utf8.RuneCountInString(query) < 2 {
		return Result{}, ErrUnavailable
	}
	params := url.Values{"q": {query}, "format": {"json"}, "language": {"fr"}, "safesearch": {"1"}}
	if youtube {
		params.Set("engines", "youtube")
	}
	b, _, err := get(ctx, c.search, c.endpoint+"/search?"+params.Encode(), "application/json", 512*1024)
	var data struct {
		Results []struct {
			Title, URL, Content string
			PublishedDate       string `json:"publishedDate"`
		} `json:"results"`
	}
	if err != nil || json.Unmarshal(b, &data) != nil {
		return Result{}, ErrUnavailable
	}
	r := Result{RetrievedAt: time.Now().UTC().Format(time.RFC3339)}
	seen := map[string]bool{}
	reads := 0
	for index, item := range data.Results {
		if index >= 5 {
			break
		}
		if len(r.Sources) == MaxSources {
			break
		}
		if !c.allowed(item.URL) || seen[item.URL] {
			continue
		}
		seen[item.URL] = true
		if youtube {
			if source, err := c.video(ctx, item.URL); err == nil {
				r.Sources = append(r.Sources, source)
			}
			continue
		}
		s := Source{Title: plain(item.Title, 160), URL: item.URL, Text: plain(item.Content, 1800), Kind: "snippet", PublishedAt: clip(item.PublishedDate, 80)}
		// Read at most two pages; inaccessible pages remain labelled as snippets.
		if reads < 2 {
			reads++
			if page, err := c.read(ctx, item.URL); err == nil {
				s = page
			}
		}
		if s.Title != "" && s.Text != "" {
			r.Sources = append(r.Sources, s)
		}
	}
	if len(r.Sources) == 0 {
		return Result{}, ErrUnavailable
	}
	if !r.Validate() {
		return Result{}, ErrUnavailable
	}
	return r, nil
}

func (c *Client) Read(ctx context.Context, target string) (Result, error) {
	if c.endpoint == "" {
		return Result{}, ErrUnavailable
	}
	s, err := c.read(ctx, target)
	if err != nil {
		return Result{}, err
	}
	r := Result{RetrievedAt: time.Now().UTC().Format(time.RFC3339), Sources: []Source{s}}
	if !r.Validate() {
		return Result{}, ErrUnavailable
	}
	return r, nil
}

var videoID = regexp.MustCompile(`^[A-Za-z0-9_-]{11}$`)

func youtubeURL(raw string) string {
	u, err := url.Parse(raw)
	if err != nil {
		return ""
	}
	host := strings.ToLower(u.Hostname())
	id := ""
	switch host {
	case "youtube.com", "www.youtube.com", "m.youtube.com":
		if u.Path == "/watch" {
			id = u.Query().Get("v")
		} else if strings.HasPrefix(u.Path, "/shorts/") {
			id = strings.TrimPrefix(u.Path, "/shorts/")
		}
	case "youtu.be":
		id = strings.TrimPrefix(u.Path, "/")
	}
	if !videoID.MatchString(id) {
		return ""
	}
	return "https://www.youtube.com/watch?v=" + id
}

func (c *Client) video(ctx context.Context, raw string) (Source, error) {
	target := youtubeURL(raw)
	if target == "" {
		return Source{}, ErrDenied
	}
	b, _, err := get(ctx, c.public, "https://www.youtube.com/oembed?format=json&url="+url.QueryEscape(target), "application/json", 32*1024)
	var data struct {
		Title, Type string
		Author      string `json:"author_name"`
		Provider    string `json:"provider_name"`
	}
	if err != nil || json.Unmarshal(b, &data) != nil || data.Type != "video" || data.Provider != "YouTube" || data.Title == "" || data.Author == "" {
		return Source{}, ErrUnavailable
	}
	return Source{Title: clip(data.Title, 160), URL: target, Kind: "video", Author: clip(data.Author, 160), Text: "Métadonnées YouTube vérifiées via oEmbed : titre et chaîne uniquement. Vidéo non regardée, aucune transcription consultée."}, nil
}
